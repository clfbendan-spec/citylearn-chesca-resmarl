CREATE TABLE IF NOT EXISTS home_source_setting (
 id INT NOT NULL PRIMARY KEY,
 community_id BIGINT NULL,
 update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
INSERT IGNORE INTO home_source_setting(id,community_id) VALUES (1,NULL);
CREATE TABLE IF NOT EXISTS home_evaluation_setting (
 id INT NOT NULL PRIMARY KEY, task_id VARCHAR(160) NULL,
 update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
INSERT IGNORE INTO home_evaluation_setting(id,task_id) VALUES (1,NULL);
CREATE TABLE IF NOT EXISTS home_realtime_measurement (
 owner_kind VARCHAR(16) NOT NULL, owner_id BIGINT NOT NULL, timestamp_ms BIGINT NOT NULL,
 payload LONGTEXT NOT NULL, received_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 PRIMARY KEY(owner_kind,owner_id,timestamp_ms)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
