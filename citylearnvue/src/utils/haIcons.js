/**
 * 根据时刻与辐照推断天气状况（CityLearn 无天气枚举，启发式贴近 HA weather state）。
 */
export function resolveWeatherCondition(row) {
  if (!row) {
    return {
      id: 'cloudy',
      label: '多云',
      labelEn: 'Cloudy',
      icon: 'weatherCloudy',
      color: '#90A4AE'
    }
  }
  const hour = row.time ? new Date(row.time).getHours() : 12
  const isNight = hour < 6 || hour >= 20
  const direct = Number(row.direct_solar_irradiance) || 0
  const diffuse = Number(row.diffuse_solar_irradiance) || 0
  const solar = direct + diffuse

  if (isNight) {
    return {
      id: 'clear-night',
      label: '晴夜',
      labelEn: 'Clear night',
      icon: 'weatherNight',
      color: '#5C6BC0'
    }
  }
  if (solar >= 600 && direct >= 350) {
    return {
      id: 'sunny',
      label: '晴',
      labelEn: 'Sunny',
      icon: 'weatherSunny',
      color: '#FF9800'
    }
  }
  if (solar >= 200) {
    return {
      id: 'partlycloudy',
      label: '局部多云',
      labelEn: 'Partly cloudy',
      icon: 'weatherPartlyCloudy',
      color: '#42A5F5'
    }
  }
  return {
    id: 'cloudy',
    label: '多云',
    labelEn: 'Cloudy',
    icon: 'weatherCloudy',
    color: '#78909C'
  }
}
